def convert_subscriptions(conn: Connection) -> None:
    subs = conn.execute(
        sa.text(
            "SELECT s.id, s.organization_id, s.catalog_item_id, s.quantity, s.price_override,"
            " s.discount_pct, s.service_identifier, s.billing_interval_months, s.auto_renew,"
            " s.status, s.vendor_party_id, s.vendor_renewal_date, s.unit_cost, s.notes,"
            " i.name AS item_name, i.cogs_account_id"
            " FROM subscription s JOIN catalog_item i ON i.id = s.catalog_item_id ORDER BY s.id"
        )
    ).all()
    for sub in subs:
        line_id = conn.execute(
            sa.text(
                "INSERT INTO subscription_line (subscription_id, sort_order, catalog_item_id,"
                " description, quantity, price_override, discount_pct)"
                " VALUES (:sub, 0, :item, :description, :quantity, :price, :discount)"
            ),
            {"sub": sub.id, "item": sub.catalog_item_id, "description": sub.item_name,
             "quantity": sub.quantity, "price": sub.price_override,
             "discount": sub.discount_pct},
        ).lastrowid  # fmt: skip
        if sub.vendor_party_id is not None:
            vendor_id = conn.execute(
                sa.text(
                    "INSERT INTO vendor_subscription (organization_id, party_id, name,"
                    " service_identifier, amount, interval_months, next_due_date,"
                    " expense_account_id, autopay, auto_renew, status, notes)"
                    " VALUES (:org, :vendor, :name, :identifier, :amount, :interval, :due,"
                    " :account, 0, :renew, :status, :notes)"
                ),
                {"org": sub.organization_id, "vendor": sub.vendor_party_id,
                 "name": sub.item_name, "identifier": sub.service_identifier,
                 "amount": (sub.unit_cost or 0) * sub.quantity,
                 "interval": sub.billing_interval_months, "due": sub.vendor_renewal_date,
                 "account": sub.cogs_account_id, "renew": sub.auto_renew,
                 "status": sub.status,
                 "notes": f"Made from client subscription {sub.id} by the 2.0 upgrade"},
            ).lastrowid  # fmt: skip
            conn.execute(
                sa.text(
                    "INSERT INTO subscription_use (subscription_line_id,"
                    " vendor_subscription_id) VALUES (:line, :vendor)"
                ),
                {"line": line_id, "vendor": vendor_id},
            )
        elif sub.unit_cost is not None or sub.vendor_renewal_date is not None:
            kept = ", ".join(
                part
                for part in (
                    f"unit cost {sub.unit_cost}" if sub.unit_cost is not None else "",
                    f"vendor renewal {sub.vendor_renewal_date}"
                    if sub.vendor_renewal_date is not None
                    else "",
                )
                if part
            )
            notes = f"{sub.notes}\n\n" if sub.notes else ""
            conn.execute(
                sa.text("UPDATE subscription SET notes = :notes WHERE id = :id"),
                {"notes": f"{notes}Before 2.0: {kept}", "id": sub.id},
            )


def restore_subscriptions(conn: Connection) -> None:
    """Back to one item per subscription: the first line, and the vendor subscription it uses.
    Further lines, packages and other vendor subscriptions are lost."""
    subs = conn.execute(sa.text("SELECT id FROM subscription")).scalars().all()
    for sub_id in subs:
        line = conn.execute(
            sa.text(
                "SELECT id, catalog_item_id, quantity, price_override, discount_pct"
                " FROM subscription_line WHERE subscription_id = :sub"
                " ORDER BY sort_order, id LIMIT 1"
            ),
            {"sub": sub_id},
        ).first()
        if line is None:
            conn.execute(
                sa.text(
                    "UPDATE invoice_line SET subscription_id = NULL WHERE subscription_id = :s"
                ),
                {"s": sub_id},
            )
            conn.execute(sa.text("DELETE FROM subscription WHERE id = :s"), {"s": sub_id})
            continue
        vendor = conn.execute(
            sa.text(
                "SELECT v.party_id, v.next_due_date, v.amount FROM subscription_use u"
                " JOIN vendor_subscription v ON v.id = u.vendor_subscription_id"
                " WHERE u.subscription_line_id = :line ORDER BY u.id LIMIT 1"
            ),
            {"line": line.id},
        ).first()
        conn.execute(
            sa.text(
                "UPDATE subscription SET catalog_item_id = :item, quantity = :quantity,"
                " price_override = :price, discount_pct = :discount, vendor_party_id = :vendor,"
                " vendor_renewal_date = :due, unit_cost = :cost WHERE id = :id"
            ),
            {"item": line.catalog_item_id, "quantity": line.quantity,
             "price": line.price_override, "discount": line.discount_pct,
             "vendor": vendor.party_id if vendor else None,
             "due": vendor.next_due_date if vendor else None,
             "cost": vendor.amount / line.quantity if vendor and line.quantity else None,
             "id": sub_id},
        )  # fmt: skip
