"""Add the copyright and license header to source files, or check that they all have it.

    python tools/license_headers.py          # add the header where it is missing
    python tools/license_headers.py --check  # list files without it; exit 1 if any (CI)

Files are those tracked by git (plus new, not ignored ones) with a known comment style.
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARKER = "SPDX-License-Identifier: GPL-3.0-or-later"

NOTICE = """\
SauMGM - Sauen Management System: billing, sales tax and bookkeeping for small businesses
Copyright (C) 2026 J. Thomas Stokkeland - https://www.saumgm.com/

This program is free software: you can redistribute it and/or modify it under the terms of the
GNU General Public License as published by the Free Software Foundation, either version 3 of
the License, or (at your option) any later version.

This program is distributed in the hope that it will be useful, but WITHOUT ANY WARRANTY;
without even the implied warranty of MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.
See the GNU General Public License for more details. You should have received a copy of the
GNU General Public License along with this program (the LICENSE file); if not, see
<https://www.gnu.org/licenses/>.

{marker}""".format(marker=MARKER)

HASH = (".py", ".sh", ".mako", ".conf", ".service", ".timer", ".yml", ".toml", ".ini")
SLASH = (".ts", ".tsx", ".cjs", ".js", ".mjs")
HTML = (".html",)

# Generated files (rewritten by tools, so a header would not survive) and data files.
SKIP = {
    "frontend/src/api/schema.d.ts",  # generated by openapi-typescript from the API
}


def hash_header() -> str:
    return "\n".join(f"# {line}".rstrip() for line in NOTICE.splitlines()) + "\n"


def slash_header() -> str:
    body = "\n".join(f" * {line}".rstrip() for line in NOTICE.splitlines())
    return f"/*\n{body}\n */\n"


def html_header() -> str:
    body = "\n".join(f"  {line}".rstrip() for line in NOTICE.splitlines())
    return f"<!--\n{body}\n-->\n"


def header_for(path: str) -> str | None:
    if path in SKIP:
        return None
    name = Path(path).name
    if name.endswith(HASH) or name == ".env.example":
        return hash_header()
    if name.endswith(SLASH):
        return slash_header()
    if name.endswith(HTML):
        return html_header()
    return None


def files() -> list[str]:
    tracked = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.splitlines()
    return sorted(p for p in tracked if (ROOT / p).is_file())


def add_header(text: str, header: str) -> str:
    lines = text.splitlines(keepends=True)
    keep: list[str] = []
    # A shebang or <!doctype> must stay on the first line.
    if lines and (lines[0].startswith("#!") or lines[0].lower().startswith("<!doctype")):
        keep.append(lines.pop(0))
    rest = "".join(lines)
    separator = "" if not rest or rest.startswith("\n") else "\n"
    return "".join(keep) + header + separator + rest


def main() -> int:
    check = "--check" in sys.argv[1:]
    missing = []
    for path in files():
        header = header_for(path)
        if header is None:
            continue
        file = ROOT / path
        text = file.read_text(encoding="utf-8")
        if MARKER in "".join(text.splitlines(keepends=True)[:25]):
            continue
        missing.append(path)
        if not check:
            file.write_text(add_header(text, header), encoding="utf-8", newline="\n")
    if check:
        for path in missing:
            print(f"missing license header: {path}")
        return 1 if missing else 0
    print(f"added the header to {len(missing)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
